package com.nichita.myvoyage.export

import android.content.Context
import java.io.File

/**
 * Каталог, куда экспортёры (PDF/Word/Excel) кладут готовые отчёты перед тем,
 * как отдать их системному «Поделиться».
 *
 * Лежит в `filesDir`, а НЕ в `cacheDir`, и это принципиально: содержимое
 * `cacheDir` Android вправе удалить сам, когда на устройстве заканчивается
 * место, и оно же стирается кнопкой «Очистить кэш» в настройках приложения.
 * Отчёты — результат работы пользователя, они должны переживать и то, и другое.
 *
 * Файлы отсюда не удаляются автоматически. Каталог приватный: другим
 * приложениям он недоступен, наружу отчёт попадает только через FileProvider
 * в момент, когда пользователь сам выбрал получателя в окне «Поделиться»
 * (см. [ReportSharing]).
 */
object ExportCache {

    /** Каталог, объявленный в res/xml/file_paths.xml. */
    fun dir(context: Context): File = File(context.filesDir, "exports")
}
